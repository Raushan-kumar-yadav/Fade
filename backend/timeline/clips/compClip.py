from __future__ import annotations
import uuid
from backend.timeline.clips.baseClip import BaseClip


class CompClip(BaseClip):
     

    CLIP_TYPE = "comp"

    def __init__(
        self,
        clipId: str = "",
        startFrame: int = 0,
        duration: int = 90,
        compId: str = "",
        mediaOffset: int = 0,
    ) -> None:
        super().__init__(
            clipId or str(uuid.uuid4()),
            startFrame,
            duration,
        )
        self.compId = compId
        self.mediaOffset = mediaOffset

    # Timeline helpers  

    def sourceFrame(self, timelineFrame: int) -> int:
        """Convert a timeline frame to the inner comp's local frame."""
        return max(0, (timelineFrame - self.startFrame) + self.mediaOffset)

    # BaseClip abstract implementations  
    def render(self, canvas, frame: int) -> None:
        """No-op: composition rendering is done by the C++ HeadlessCompositor."""
        pass

    def getThumbnail(self, frame: int, width: int = 160, height: int = 90) -> bytes:
        """Return empty bytes; comp thumbnails are not generated by Python."""
        return b""

    #   Serialization  
    def toDict(self) -> dict:
        # Resolve the kind of the referenced comp so the frontend knows
        # whether to open the image editor or video editor on double-click.
        comp_kind = "video"
        try:
            from backend.state import engine
            if engine.project:
                for tl in engine.project.timelines:
                    if getattr(tl, "compId", None) == self.compId:
                        comp_kind = getattr(tl, "kind", "video") or "video"
                        break
        except Exception:
            pass

        return {
            "type": self.CLIP_TYPE,
            "clipId": self.clipId,
            "startFrame": self.startFrame,
            "duration": self.duration,
            "compId": self.compId,
            "compKind": comp_kind,
            "mediaOffset": self.mediaOffset,
            "transform": self.transform.toDict(),
            "effects": [e.toDict() for e in self.effects],
        }


    @classmethod
    def fromDict(cls, data: dict) -> "CompClip":
        from backend.animation.transform import Transform
        c = cls(
            clipId=data["clipId"],
            startFrame=data["startFrame"],
            duration=data["duration"],
            compId=data.get("compId", ""),
            mediaOffset=data.get("mediaOffset", 0),
        )
        if "transform" in data:
            c.transform = Transform.fromDict(data["transform"])
        return c
